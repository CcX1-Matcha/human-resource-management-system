/* Optional browser acceptance check: set PLAYWRIGHT_PATH and HRM_TEST_URL.
   Run against a dedicated demonstration database, never a live personnel database. */
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const baseURL = process.env.HRM_TEST_URL || 'http://127.0.0.1:8031';

(async () => {
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  const context = await browser.newContext({viewport:{width:1440,height:1080}});
  const page = await context.newPage();
  const errors = [];
  const qaName = '浏览器验收员工'+Date.now();
  const birthdayDate = new Date(Date.now()+4*86400000);
  const birthday = '1996-'+String(birthdayDate.getMonth()+1).padStart(2,'0')+'-'+String(birthdayDate.getDate()).padStart(2,'0');
  page.on('pageerror',error=>errors.push(error.message));
  try {
    await page.goto(baseURL);
    await page.locator('#password').fill('Admin123!');
    await page.locator('#login-form button').click();
    await page.locator('.metrics-grid').waitFor();
    assert.equal(await page.locator('.metric-card').count(),4);
    await page.goto(baseURL+'/#/records/employees');
    await page.locator('#new-record').click();
    await page.locator('#field-name').fill(qaName);
    await page.locator('#field-employee_no').fill('QA'+Date.now());
    await page.locator('#field-department_id').selectOption({label:'研发中心'});
    await page.locator('#field-hire_date').fill((new Date().getFullYear()-1)+'-01-05');
    await page.locator('#field-birthday').fill(birthday);
    await page.locator('#field-base_salary').fill('10000');
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({state:'hidden'});
    await page.locator('#filter-form input[name=q]').fill(qaName);
    await page.locator('#filter-form button[type=submit]').click();
    await page.locator('.record-table tbody tr').waitFor();
    assert.equal(await page.locator('.record-table tbody tr').count(),1);
    const [csvDownload] = await Promise.all([page.waitForEvent('download'),page.locator('#export-records').click()]);
    assert.ok(csvDownload.suggestedFilename().includes('员工档案'));
    await page.locator('[data-edit]').click();
    await page.locator('#field-position').fill('测试工程师');
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({state:'hidden'});
    assert.ok((await page.locator('.record-table').textContent()).includes('测试工程师'));
    await page.locator('[data-view]').click();
    assert.ok((await page.locator('#record-dialog').textContent()).includes('研发中心'));
    await page.locator('#record-dialog [data-close-dialog]').first().click();
    await page.goto(baseURL+'/#/birthdays');
    await page.locator('#birthday-filter').waitFor();
    assert.ok((await page.locator('#page-content').textContent()).includes(birthday.replaceAll('-','.')));
    await page.goto(baseURL+'/#/reports');
    await page.locator('#export-reports').waitFor();
    assert.equal(await page.locator('.stats-grid .panel').count(),9);
    await page.goto(baseURL+'/#/records/insurance_rates');
    await page.locator('[data-edit]').first().click();
    assert.equal(await page.locator('#field-employee_rate').evaluate(input=>input.checkValidity()),true);
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({state:'hidden'});
    const metadata = await page.evaluate(async()=> (await (await fetch('/api/meta')).json()));
    for (const [key,resource] of Object.entries(metadata.resources)) {
      await page.goto(baseURL+'/#/records/'+key);
      await page.locator('#filter-form').waitFor();
      assert.ok((await page.locator('h1').textContent()).includes(resource.title),key+' page heading');
      if (key!=='payroll') {
        await page.locator('#new-record').click();
        await page.locator('#record-form').waitFor();
        assert.equal(await page.locator('#record-form .field').count(),resource.fields.filter(field=>!field.readonly&&field.name!=='id').length,key+' form fields');
        await page.locator('#record-dialog [data-close-dialog]').first().click();
      }
    }
    await page.goto(baseURL+'/#/records/menus');
    await page.locator('#filter-form input[name=q]').fill('人事管理');
    await page.locator('#filter-form button[type=submit]').click();
    await page.locator('[data-edit]').click();
    await page.locator('#field-name').fill('员工事务');
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({state:'hidden'});
    await page.locator('[data-module="personnel"]').filter({hasText:'员工事务'}).waitFor();
    await page.locator('#reset-filters').click();
    await page.locator('#filter-form input[name=q]').fill('员工事务');
    await page.locator('#filter-form button[type=submit]').click();
    await page.locator('[data-edit]').click();
    await page.locator('#field-name').fill('人事管理');
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({state:'hidden'});
    await page.locator('[data-module="personnel"]').filter({hasText:'人事管理'}).waitFor();
    await page.goto(baseURL+'/#/records/dictionaries');
    await page.locator('#new-record').click();
    await page.locator('#field-category').fill('学历');
    await page.locator('#field-code').fill('qa_'+Date.now());
    await page.locator('#field-label').fill('职业本科验收');
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({state:'hidden'});
    await page.goto(baseURL+'/#/records/employees');
    await page.locator('#new-record').click();
    await page.locator('#field-education').selectOption({label:'职业本科验收'});
    await page.locator('#record-dialog [data-close-dialog]').first().click();
    await page.goto(baseURL+'/#/records/payroll');
    await page.locator('#generate-payroll').click();
    await page.locator('#confirm-accept').click();
    await page.locator('#generate-payroll:not(:disabled)').waitFor();
    assert.ok(await page.locator('.record-table tbody tr').count()>0);
    await page.locator('[data-pay]').first().click();
    await page.locator('#confirm-accept').click();
    await page.getByText('已锁定').first().waitFor();
    await page.goto(baseURL+'/#/records/notices');
    await page.locator('[data-view]').first().click();
    await page.evaluate(()=>{window.print=()=>{window.__printed=true;};});
    await page.locator('#print-notice').click();
    assert.equal(await page.evaluate(()=>window.__printed),true);
    assert.ok((await page.locator('.print-target').textContent()).includes('工资核对与发放说明'));
    await page.locator('#record-dialog [data-close-dialog]').first().click();
    await page.locator('#new-record').click();
    await page.locator('#field-title').fill('浏览器验收通知'+Date.now());
    await page.locator('#field-content').fill('这是自动验收时创建的临时通知。');
    const date = new Date();
    await page.locator('#field-date').fill(date.getFullYear()+'-'+String(date.getMonth()+1).padStart(2,'0')+'-'+String(date.getDate()).padStart(2,'0'));
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({state:'hidden'});
    await page.locator('[data-delete]').first().click();
    await page.locator('#confirm-accept').click();
    await page.locator('.toast').filter({hasText:'记录已删除'}).waitFor();
    await page.goto(baseURL+'/#/records/employees');
    await page.locator('#filter-form input[name=q]').fill(qaName);
    await page.locator('#filter-form button[type=submit]').click();
    await page.locator('[data-delete]').click();
    await page.locator('#confirm-accept').click();
    await page.locator('.toast.error').waitFor();
    assert.ok((await page.locator('.toast.error').last().textContent()).includes('引用'));
    await page.goto(baseURL+'/#/dashboard');
    await page.locator('.metrics-grid').waitFor();
    await page.evaluate(()=>document.querySelector('#toast-region').replaceChildren());
    if(process.env.HRM_SCREENSHOT_DIR)await page.screenshot({path:process.env.HRM_SCREENSHOT_DIR+'/hrm-dashboard.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    await page.locator('[data-toggle-nav]').click();
    assert.ok(await page.locator('.app-shell').evaluate(el=>el.classList.contains('nav-open')));
    await page.locator('[data-close-nav]').click({position:{x:280,y:30}});
    await page.locator('#logout-button').click();
    await page.locator('#confirm-accept').click();
    await page.locator('#username').waitFor();
    await page.locator('#username').fill('viewer');
    await page.locator('#password').fill('View123456!');
    await page.locator('#login-form button').click();
    await page.locator('.metrics-grid').waitFor();
    assert.equal(await page.locator('[data-module="settings"]').count(),0);
    assert.equal(await page.locator('[data-module="payroll"]').count(),0);
    await page.goto(baseURL+'/#/records/notices');
    await page.locator('#filter-form').waitFor();
    assert.equal(await page.locator('#new-record').count(),0);
    assert.equal(await page.locator('[data-edit]').count(),0);
    await page.goto(baseURL+'/#/query/employees');
    await page.locator('#filter-form').waitFor();
    assert.equal(await page.locator('#new-record').count(),0);
    assert.deepEqual(errors,[]);
    console.log('Browser acceptance passed: authentication, employee create/update/filter/detail, birthday dates, eight reports, all metadata pages/forms, live navigation and dictionary settings, decimal rates, payroll generation/payment, notice print, related-record delete protection, mobile layout, viewer navigation/write restrictions.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
